// 4. CLI
// ---------------------------------------------------------------------------

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function main(): void {
  const check = selfCheck();
  console.log(
    `vector self-check: ${check.cases} committed Python pool cases replayed through ` +
    `backend/scoring — scores, zones, ranks, leaf order and payout list all match; ` +
    `${check.withTree} of them also match leaf bytes and the Merkle root.`
  );
  if (process.argv.includes('--check-only')) return;

  const FIELDS: Record<string, () => PlannedSeat[]> = { T3: t3Field, T4: t4Field, T5: t5Field, T6: t6Field, T7: t7Field };
  const PLANS: Record<string, (p: Prediction) => Record<string, unknown>> = {
    T3: t3Plan, T4: t4Plan, T5: t5Plan, T6: t6Plan, T7: t7Plan,
  };
  const known = Object.keys(FIELDS).join('|');

  const test = flag('test') ?? fail(`--test <${known}> is required`);
  const buildField = FIELDS[test] ?? fail(`no field is defined for ${test} — only ${known}`);

  const entryLamports = 100_000_000n; // tier 0, read from chain and from the plan
  const p = predict(buildField(), entryLamports);

  console.log(`\n${test} — ${p.seats.length} seats · pot ${p.potLamports} lamports · entry ${p.entryLamports}\n`);
  console.log('seat  wallet  role    rank   score  zones   shapes  round%  lamports');
  for (const s of p.seats) {
    if (s.role === 'field' && s.plannedSeat > 5 && s.plannedSeat < p.seats.length - 2) continue;
    console.log(
      `${String(s.plannedSeat).padStart(4)}  ${s.wallet.padEnd(6)}  ${s.role.padEnd(6)}  ` +
      `${String(s.rank).padStart(4)}  ${String(s.scoreHalf).padStart(6)}  ${String(s.zones).padStart(5)}  ` +
      `${String(s.distinctShapes).padStart(6)}  ${String(Math.round(s.roundShare * 100)).padStart(6)}  ${s.amountLamports}`
    );
    if (s.plannedSeat === 5) console.log('  ..    (54 more field seats)');
  }

  const ranks = p.seats.map((s) => s.rank);
  console.log(`\nrank spread: best ${Math.min(...ranks)} · worst ${Math.max(...ranks)}`);
  console.log(`paid seats: ${p.paidSeats.map((s) => `${s.wallet} rank ${s.rank} → ${s.amountLamports}`).join(', ')}`);
  console.log(`results root (conditional on the planned seat order): ${p.resultsRoot}`);

  const emit = flag('emit');
  if (emit) {
    writeFileSync(emit, JSON.stringify(p, null, 2) + '\n');
    console.log(`\nwrote ${emit}`);
  }

  const planOut = flag('plan');
  if (planOut) {
    writeFileSync(planOut, JSON.stringify(PLANS[test](p), null, 2) + '\n');
    console.log(`wrote ${planOut}`);
  }
}

if (require.main === module) main();
