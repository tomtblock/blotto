export interface PlannedSeat {
  /** Roster id, e.g. `UI-A` or `W07`. */
  wallet: string;
  /** `ui` (the founder, through the live site) or `direct` (enter.ts). */
  route: 'ui' | 'direct';
  /** The part this seat plays in the engineered outcome. */
  role: 'wall' | 'pole' | 'field';
  generator: string;
  /** Absent on the two UI seats: those come from a drag recipe, not a seed. */
  seed?: number;
  /** The founder's drag list, on the UI seats only. */
  recipe?: string;
  battles: number[][];
  timingsMs: number[];
}

/** Fixed here and never moved: the plan is frozen against these. */
const T4_FIELD_SEED_BASE = 4000;

/**
 * T4's 64 seats, in the order they are intended to register.
 *
 * Order matters for exactly one thing — the seat index each wallet lands on,
 * which fixes the Merkle leaf order and therefore the results root. It does
 * NOT affect any rank: a rank falls out of the allocations alone. So a seat
 * order that comes out differently on the day costs the root prediction and
 * nothing else, and the plan says so rather than pretending otherwise.
 */
export function t4Field(): PlannedSeat[] {
  const seats: PlannedSeat[] = [];
  const add = (
    wallet: string,
    route: 'ui' | 'direct',
    role: PlannedSeat['role'],
    e: Entrant,
    extra: { seed?: number; recipe?: string }
  ) =>
    seats.push({ wallet, route, role, generator: e.generator, battles: e.battles, timingsMs: e.timingsMs, ...extra });

  // The founder enters first, through the live site, as they did for T1. These
  // two use `uiWall`/`uiPole` rather than the seeded generators: they have to
  // be typed into the live dials inside a 90-second run clock, so the plan
  // predicts sets the dials can actually reach in one or two drags each.
  add('UI-A', 'ui', 'wall', uiWall(), {
    recipe: 'each battle, drag two stats to 0 — pairs in order: Strength+Speed, Speed+Heart, Heart+Wit, Wit+Durability, Durability+Strength, Strength+Heart, Speed+Wit',
  });
  add('UI-B', 'ui', 'pole', uiPole(), {
    recipe: 'each battle, drag one stat to 100 — in order: Strength, Speed, Heart, Wit, Durability, Heart, Strength',
  });
  // Then 62 headless seats, W00 through W61.
  for (let i = 0; i < 62; i++) {
    const seed = T4_FIELD_SEED_BASE + i;
    add(`W${String(i).padStart(2, '0')}`, 'direct', 'field', cappedField(seed), { seed });
  }
  return seats;
}

