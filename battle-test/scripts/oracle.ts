export interface SeatPrediction extends PlannedSeat {
  /** Intended seat index — what `register` assigns if entries land in plan order. */
  plannedSeat: number;
  address: string;
  scoreHalf: number;
  zones: number;
  rank: number;
  amountLamports: string;
  distinctShapes: number;
  roundShare: number;
}

export interface Prediction {
  entryLamports: string;
  potLamports: string;
  seats: SeatPrediction[];
  /** Seat indices in published leaf order (rank asc, seat asc). */
  leafOrder: number[];
  /** Conditional on the planned seat order — see `t4Field`. */
  resultsRoot: string;
  paidSeats: { wallet: string; plannedSeat: number; rank: number; amountLamports: string }[];
}

function addressesFromRoster(): Map<string, string> {
  const doc = JSON.parse(readFileSync(resolve(REG, 'wallets.json'), 'utf8')) as {
    wallets: { id: string; address: string }[];
  };
  return new Map(doc.wallets.map((w) => [w.id, w.address]));
}

export function predict(field: PlannedSeat[], entryLamports: bigint): Prediction {
  const pot = potForEntry(entryLamports);
  const roster = addressesFromRoster();

  const scored: PlayerResult[] = assignPrizes(
    scorePool(asBattleSet(field.map((s) => s.battles))),
    pot
  );

  const seats: SeatPrediction[] = field.map((s, i) => {
    const address = roster.get(s.wallet) ?? fail(`${s.wallet} is not in registry/wallets.json`);
    return {
      ...s,
      plannedSeat: i,
      address,
      scoreHalf: scored[i].scoreHalf,
      zones: scored[i].zones,
      rank: scored[i].rank,
      amountLamports: scored[i].amountLamports.toString(),
      distinctShapes: distinctShapes(s.battles),
      roundShare: Math.round(roundShare(s.battles) * 100) / 100,
    };
  });

  const leafOrder = rankOrder(scored);
  const leaves = leafOrder.map((seat) =>
    leafBytes({
      player: bs58.decode(seats[seat].address),
      rank: scored[seat].rank,
      amountLamports: scored[seat].amountLamports,
    })
  );

  return {
    entryLamports: entryLamports.toString(),
    potLamports: pot.toString(),
    seats,
    leafOrder,
    resultsRoot: hex(merkleRoot(leaves)),
    paidSeats: seats
      .filter((s) => s.amountLamports !== '0')
      .map((s) => ({ wallet: s.wallet, plannedSeat: s.plannedSeat, rank: s.rank, amountLamports: s.amountLamports })),
  };
}


