const hex = (b: Uint8Array): string => Buffer.from(b).toString('hex');
const fail = (m: string): never => { throw new Error(m); };

/** `number[][]` from a generator into the engine's nominal tuple type. */
const asBattleSet = (battles: number[][]): BattleSet =>
  battles.map((b) => b as unknown as EngineAllocation);

// ---------------------------------------------------------------------------
// 1. The self-check: our engine against the committed Python vectors
// ---------------------------------------------------------------------------

interface VectorResult { index: number; score_half: number; zones: number; rank: number; amount_lamports: string }
interface VectorPool {
  name: string;
  entry_lamports: string;
  players: { battles: number[][] }[];
  results: VectorResult[];
  leaf_order: string;
  payouts: { entry_index: number; amount: string }[];
  players_pubkeys?: string[];
  amounts?: string[];
  leaves_hex?: string[];
  root?: string;
}

/**
 * Replay every committed pool vector through our engine. Throws on the first
 * disagreement, naming the case and the field — a silent near-miss here would
 * put a wrong prediction into a frozen plan.
 */
function selfCheck(): { cases: number; withTree: number } {
  const doc = JSON.parse(readFileSync(resolve(SCORING, 'fixtures', 'vectors.json'), 'utf8')) as {
    pools: VectorPool[];
  };
  let withTree = 0;

  for (const v of doc.pools) {
    const pot = potForEntry(BigInt(v.entry_lamports));
    const scored = scorePool(asBattleSet(v.players.map((p) => p.battles)));
    const paid = assignPrizes(scored, pot);

    if (paid.length !== v.results.length) {
      fail(`${v.name}: engine returned ${paid.length} results, the vector has ${v.results.length}`);
    }
    for (const want of v.results) {
      const got = paid[want.index];
      if (got.index !== want.index) fail(`${v.name} seat ${want.index}: results are not in seat order`);
      if (got.scoreHalf !== want.score_half) {
        fail(`${v.name} seat ${want.index}: scoreHalf ${got.scoreHalf}, vector says ${want.score_half}`);
      }
      if (got.zones !== want.zones) {
        fail(`${v.name} seat ${want.index}: zones ${got.zones}, vector says ${want.zones}`);
      }
      if (got.rank !== want.rank) {
        fail(`${v.name} seat ${want.index}: rank ${got.rank}, vector says ${want.rank}`);
      }
      if (got.amountLamports !== BigInt(want.amount_lamports)) {
        fail(`${v.name} seat ${want.index}: amount ${got.amountLamports}, vector says ${want.amount_lamports}`);
      }
    }

    const order = rankOrder(paid).join(',');
    if (order !== v.leaf_order) fail(`${v.name}: leaf order ${order}, vector says ${v.leaf_order}`);

    const payouts = paid
      .filter((r) => r.amountLamports > 0n)
      .sort((a, b) => a.index - b.index)
      .map((r) => `${r.index}:${r.amountLamports}`)
      .join(' ');
    const wantPayouts = v.payouts.map((p) => `${p.entry_index}:${p.amount}`).join(' ');
    if (payouts !== wantPayouts) {
      fail(`${v.name}: payout list [${payouts}], vector says [${wantPayouts}]`);
    }

    // The tree, where the vector carries one.
    if (v.root && v.players_pubkeys && v.leaves_hex) {
      withTree++;
      const byRank = rankOrder(paid);
      const leaves = byRank.map((seat) =>
        leafBytes({
          player: Buffer.from(v.players_pubkeys![seat], 'hex'),
          rank: paid[seat].rank,
          amountLamports: paid[seat].amountLamports,
        })
      );
      leaves.forEach((l, i) => {
        if (hex(l) !== v.leaves_hex![i]) fail(`${v.name} leaf ${i}: ${hex(l)} != ${v.leaves_hex![i]}`);
      });
      const root = hex(merkleRoot(leaves));
      if (root !== v.root) fail(`${v.name}: root ${root}, vector says ${v.root}`);
    }
  }

  return { cases: doc.pools.length, withTree };
}

