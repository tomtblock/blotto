/**
 * oracle.ts — the prediction, computed with the product's own engine.
 *
 * A scored test has to say, BEFORE anyone enters, who wins and what they are
 * paid. This computes that. It deliberately adds no scoring logic of its own:
 * every number here comes from `backend/scoring`, imported by relative path as
 * a read-only library, so the prediction and the settlement crank are running
 * the same code. An oracle that re-implemented the rule could agree with the
 * plan and disagree with the chain.
 *
 * Because that shared code is the single point of failure, the FIRST thing
 * this does is check it against `backend/scoring/fixtures/vectors.json` — the
 * committed Python vectors, generated by `gen_vectors.py` from an independent
 * implementation. A vector captured from our own TypeScript output would prove
 * nothing; these were not. The self-check covers all 36 pool cases end to end:
 * scores, zones, ranks, the leaf order, the committed payout list, and for the
 * 16 cases that carry one, the leaf bytes and the Merkle root.
 *
 * Run:
 *   npx ts-node --transpile-only --compiler-options \
 *     '{"module":"commonjs","moduleResolution":"node"}' scripts/oracle.ts --test T4
 *
 * Flags:
 *   --test <id>    which test's field to predict — T3, T4, T5 or T6
 *   --check-only   run the vector self-check and stop
 *   --emit <path>  write the prediction as JSON for the plan builder
 */

