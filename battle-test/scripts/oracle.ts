/**
 * oracle.ts — the prediction, computed with the product's own engine.
 *
 * A scored test has to say, BEFORE anyone enters, who wins and what they are
 * paid. This computes that. It deliberately adds no scoring logic of its own:
 * every number here comes from `backend/scoring`, imported by relative path as
 * a read-only library, so the prediction and the settlement crank are running
 * the same code. An oracle that re-implemented the rule could agree with the
 * plan and disagree with the chain.
 *
 * Because that shared code is the single point of failure, the FIRST thing
 * this does is check it against `backend/scoring/fixtures/vectors.json` — the
 * committed Python vectors, generated by `gen_vectors.py` from an independent
 * implementation. A vector captured from our own TypeScript output would prove
 * nothing; these were not. The self-check covers all 36 pool cases end to end:
 * scores, zones, ranks, the leaf order, the committed payout list, and for the
 * 16 cases that carry one, the leaf bytes and the Merkle root.
 *
 * Run:
 *   npx ts-node --transpile-only --compiler-options \
 *     '{"module":"commonjs","moduleResolution":"node"}' scripts/oracle.ts --test T4
 *
 * Flags:
 *   --test <id>    which test's field to predict (T4 today)
 *   --check-only   run the vector self-check and stop
 *   --emit <path>  write the prediction as JSON for the plan builder
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import bs58 from 'bs58';

import {
  scorePool,
  assignPrizes,
  rankOrder,
  type PlayerResult,
} from '../../backend/scoring/src/engine';
import { potForEntry } from '../../backend/scoring/src/prizes';
import { leafBytes, merkleRoot } from '../../backend/scoring/src/merkle';
import type { BattleSet, Allocation as EngineAllocation } from '../../backend/scoring/src/allocation';

import { cappedField, uiWall, uiPole, distinctShapes, roundShare, type Entrant } from '../src/populations';

const SCORING = resolve(__dirname, '..', '..', 'backend', 'scoring');
const REG = resolve(__dirname, '..', 'registry');

const hex = (b: Uint8Array): string => Buffer.from(b).toString('hex');
const fail = (m: string): never => { throw new Error(m); };

/** `number[][]` from a generator into the engine's nominal tuple type. */
const asBattleSet = (battles: number[][]): BattleSet =>
  battles.map((b) => b as unknown as EngineAllocation);

// ---------------------------------------------------------------------------
// 1. The self-check: our engine against the committed Python vectors
// ---------------------------------------------------------------------------

interface VectorResult { index: number; score_half: number; zones: number; rank: number; amount_lamports: string }
interface VectorPool {
  name: string;
  entry_lamports: string;
  players: { battles: number[][] }[];
  results: VectorResult[];
  leaf_order: string;
  payouts: { entry_index: number; amount: string }[];
  players_pubkeys?: string[];
  amounts?: string[];
  leaves_hex?: string[];
  root?: string;
}

/**
 * Replay every committed pool vector through our engine. Throws on the first
 * disagreement, naming the case and the field — a silent near-miss here would
 * put a wrong prediction into a frozen plan.
 */
function selfCheck(): { cases: number; withTree: number } {
  const doc = JSON.parse(readFileSync(resolve(SCORING, 'fixtures', 'vectors.json'), 'utf8')) as {
    pools: VectorPool[];
  };
  let withTree = 0;

  for (const v of doc.pools) {
    const pot = potForEntry(BigInt(v.entry_lamports));
    const scored = scorePool(asBattleSet(v.players.map((p) => p.battles)));
    const paid = assignPrizes(scored, pot);

    if (paid.length !== v.results.length) {
      fail(`${v.name}: engine returned ${paid.length} results, the vector has ${v.results.length}`);
    }
    for (const want of v.results) {
      const got = paid[want.index];
      if (got.index !== want.index) fail(`${v.name} seat ${want.index}: results are not in seat order`);
      if (got.scoreHalf !== want.score_half) {
        fail(`${v.name} seat ${want.index}: scoreHalf ${got.scoreHalf}, vector says ${want.score_half}`);
      }
      if (got.zones !== want.zones) {
        fail(`${v.name} seat ${want.index}: zones ${got.zones}, vector says ${want.zones}`);
      }
      if (got.rank !== want.rank) {
        fail(`${v.name} seat ${want.index}: rank ${got.rank}, vector says ${want.rank}`);
      }
      if (got.amountLamports !== BigInt(want.amount_lamports)) {
        fail(`${v.name} seat ${want.index}: amount ${got.amountLamports}, vector says ${want.amount_lamports}`);
      }
    }

    const order = rankOrder(paid).join(',');
    if (order !== v.leaf_order) fail(`${v.name}: leaf order ${order}, vector says ${v.leaf_order}`);

    const payouts = paid
      .filter((r) => r.amountLamports > 0n)
      .sort((a, b) => a.index - b.index)
      .map((r) => `${r.index}:${r.amountLamports}`)
      .join(' ');
    const wantPayouts = v.payouts.map((p) => `${p.entry_index}:${p.amount}`).join(' ');
    if (payouts !== wantPayouts) {
      fail(`${v.name}: payout list [${payouts}], vector says [${wantPayouts}]`);
    }

    // The tree, where the vector carries one.
    if (v.root && v.players_pubkeys && v.leaves_hex) {
      withTree++;
      const byRank = rankOrder(paid);
      const leaves = byRank.map((seat) =>
        leafBytes({
          player: Buffer.from(v.players_pubkeys![seat], 'hex'),
          rank: paid[seat].rank,
          amountLamports: paid[seat].amountLamports,
        })
      );
      leaves.forEach((l, i) => {
        if (hex(l) !== v.leaves_hex![i]) fail(`${v.name} leaf ${i}: ${hex(l)} != ${v.leaves_hex![i]}`);
      });
      const root = hex(merkleRoot(leaves));
      if (root !== v.root) fail(`${v.name}: root ${root}, vector says ${v.root}`);
    }
  }

  return { cases: doc.pools.length, withTree };
}

// ---------------------------------------------------------------------------
// 2. The field
// ---------------------------------------------------------------------------

export interface PlannedSeat {
  /** Roster id, e.g. `UI-A` or `W07`. */
  wallet: string;
  /** `ui` (the founder, through the live site) or `direct` (enter.ts). */
  route: 'ui' | 'direct';
  /** The part this seat plays in the engineered outcome. */
  role: 'wall' | 'pole' | 'field';
  generator: string;
  /** Absent on the two UI seats: those come from a drag recipe, not a seed. */
  seed?: number;
  /** The founder's drag list, on the UI seats only. */
  recipe?: string;
  battles: number[][];
  timingsMs: number[];
}

/** Fixed here and never moved: the plan is frozen against these. */
const T4_FIELD_SEED_BASE = 4000;

/**
 * T4's 64 seats, in the order they are intended to register.
 *
 * Order matters for exactly one thing — the seat index each wallet lands on,
 * which fixes the Merkle leaf order and therefore the results root. It does
 * NOT affect any rank: a rank falls out of the allocations alone. So a seat
 * order that comes out differently on the day costs the root prediction and
 * nothing else, and the plan says so rather than pretending otherwise.
 */
export function t4Field(): PlannedSeat[] {
  const seats: PlannedSeat[] = [];
  const add = (
    wallet: string,
    route: 'ui' | 'direct',
    role: PlannedSeat['role'],
    e: Entrant,
    extra: { seed?: number; recipe?: string }
  ) =>
    seats.push({ wallet, route, role, generator: e.generator, battles: e.battles, timingsMs: e.timingsMs, ...extra });

  // The founder enters first, through the live site, as they did for T1. These
  // two use `uiWall`/`uiPole` rather than the seeded generators: they have to
  // be typed into the live dials inside a 90-second run clock, so the plan
  // predicts sets the dials can actually reach in one or two drags each.
  add('UI-A', 'ui', 'wall', uiWall(), {
    recipe: 'each battle, drag two stats to 0 — pairs in order: Strength+Speed, Speed+Heart, Heart+Wit, Wit+Durability, Durability+Strength, Strength+Heart, Speed+Wit',
  });
  add('UI-B', 'ui', 'pole', uiPole(), {
    recipe: 'each battle, drag one stat to 100 — in order: Strength, Speed, Heart, Wit, Durability, Heart, Strength',
  });
  // Then 62 headless seats, W00 through W61.
  for (let i = 0; i < 62; i++) {
    const seed = T4_FIELD_SEED_BASE + i;
    add(`W${String(i).padStart(2, '0')}`, 'direct', 'field', cappedField(seed), { seed });
  }
  return seats;
}

// ---------------------------------------------------------------------------
// 3. The prediction
// ---------------------------------------------------------------------------

export interface SeatPrediction extends PlannedSeat {
  /** Intended seat index — what `register` assigns if entries land in plan order. */
  plannedSeat: number;
  address: string;
  scoreHalf: number;
  zones: number;
  rank: number;
  amountLamports: string;
  distinctShapes: number;
  roundShare: number;
}

export interface Prediction {
  entryLamports: string;
  potLamports: string;
  seats: SeatPrediction[];
  /** Seat indices in published leaf order (rank asc, seat asc). */
  leafOrder: number[];
  /** Conditional on the planned seat order — see `t4Field`. */
  resultsRoot: string;
  paidSeats: { wallet: string; plannedSeat: number; rank: number; amountLamports: string }[];
}

function addressesFromRoster(): Map<string, string> {
  const doc = JSON.parse(readFileSync(resolve(REG, 'wallets.json'), 'utf8')) as {
    wallets: { id: string; address: string }[];
  };
  return new Map(doc.wallets.map((w) => [w.id, w.address]));
}

export function predict(field: PlannedSeat[], entryLamports: bigint): Prediction {
  const pot = potForEntry(entryLamports);
  const roster = addressesFromRoster();

  const scored: PlayerResult[] = assignPrizes(
    scorePool(asBattleSet(field.map((s) => s.battles))),
    pot
  );

  const seats: SeatPrediction[] = field.map((s, i) => {
    const address = roster.get(s.wallet) ?? fail(`${s.wallet} is not in registry/wallets.json`);
    return {
      ...s,
      plannedSeat: i,
      address,
      scoreHalf: scored[i].scoreHalf,
      zones: scored[i].zones,
      rank: scored[i].rank,
      amountLamports: scored[i].amountLamports.toString(),
      distinctShapes: distinctShapes(s.battles),
      roundShare: Math.round(roundShare(s.battles) * 100) / 100,
    };
  });

  const leafOrder = rankOrder(scored);
  const leaves = leafOrder.map((seat) =>
    leafBytes({
      player: bs58.decode(seats[seat].address),
      rank: scored[seat].rank,
      amountLamports: scored[seat].amountLamports,
    })
  );

  return {
    entryLamports: entryLamports.toString(),
    potLamports: pot.toString(),
    seats,
    leafOrder,
    resultsRoot: hex(merkleRoot(leaves)),
    paidSeats: seats
      .filter((s) => s.amountLamports !== '0')
      .map((s) => ({ wallet: s.wallet, plannedSeat: s.plannedSeat, rank: s.rank, amountLamports: s.amountLamports })),
  };
}


