#!/usr/bin/env python3
"""Generate the known-answer vectors for `blotto-randomness`.

Run from the crate root:

    python3 fixtures/gen_vectors.py > fixtures/vectors.json

or in place:

    python3 fixtures/gen_vectors.py --write

Why this script exists
----------------------
The Rust tests must be checked against digests computed by something that is **not**
this crate. A vector captured from our own Rust output proves only that the crate
agrees with itself; it would happily lock in a byte order that is wrong everywhere.

The predecessor repository knew this and computed its vectors with Python `hashlib`
— but it inlined the resulting bytes into the test file and **never committed the
generator**, so nobody after the fact could regenerate them, verify their provenance,
or extend the set. That gap is the reason this file is here. It is committed
alongside `vectors.json`, and `vectors.json` is regenerated by running it.

Everything below uses only the Python standard library, deliberately: no
dependency, no environment, no version drift. Any reviewer with a Python
interpreter can rerun it and diff the result against the committed JSON.

What it generates
-----------------
1. `derive` vectors — SHA-256 over the canonical 130-byte input stream:

       vrf_seed(32) || slot_hash(32) || entry_index(2, LE) || pool_pubkey(32) || player_pubkey(32)

   Three input shapes, mirroring the three the old crate used, re-pointed at the
   new pool geometry: constant bytes at the first seat, constant bytes at the last
   seat (index 63 of 64), and progressive bytes at index 1.

2. `draw` vectors — one per cosmetic class, each pinning `weighted_class_draw` to a
   specific index under the launch counters. With CLASS_COUNTERS = [38, 15, 7, 3, 1]
   (sum 64) the cumulative ranges are:

       index 0  Goblin  [ 0, 38)
       index 1  Knight  [38, 53)
       index 2  Wizard  [53, 60)
       index 3  Dragon  [60, 63)
       index 4  Titan   [63, 64)

   Each vector supplies a `u64` whose value mod 64 lands in exactly one range, and
   records the expected index. The `rng_bytes` are that `u64` little-endian in the
   first 8 bytes, zero elsewhere — mirroring how the Rust function decodes them.
"""

import argparse
import hashlib
import json
import os
import sys

# Cosmetic character classes, in the fixed order the counters array uses.
# PID §3. Class is cosmetic only and is read by nothing in the scoring path.
CLASS_NAMES = ["Goblin", "Knight", "Wizard", "Dragon", "Titan"]

# Launch counters, PID §3 / TECH-ARCH §2. Sum = 64 = one pool's seats.
CLASS_COUNTERS = [38, 15, 7, 3, 1]

# Seats per pool. The last seat is index 63.
CAPACITY = 64


def derive_class_randomness(vrf_seed, slot_hash, entry_index, pool_pubkey, player_pubkey):
    """SHA-256 over the canonical 130-byte stream. See TECH-ARCH §4.

    `entry_index` is little-endian, matching Borsh's default integer encoding —
    the Anchor/Solana account-serialization convention — so on-chain code stays
    consistent with its own `Entry.index` byte layout with no separate conversion.
    """
    for name, value in (
        ("vrf_seed", vrf_seed),
        ("slot_hash", slot_hash),
        ("pool_pubkey", pool_pubkey),
        ("player_pubkey", player_pubkey),
    ):
        if len(value) != 32:
            raise ValueError(f"{name} must be 32 bytes, got {len(value)}")
    if not 0 <= entry_index <= 0xFFFF:
        raise ValueError(f"entry_index must fit in a u16, got {entry_index}")

    stream = (
        vrf_seed
        + slot_hash
        + entry_index.to_bytes(2, "little")
        + pool_pubkey
        + player_pubkey
    )
    assert len(stream) == 130, f"canonical stream must be 130 bytes, got {len(stream)}"
    return hashlib.sha256(stream).digest()


def expected_class_index(n, counters):
    """Reproduce the Rust cumulative walk: `n % total`, then walk the counters."""
    total = sum(counters)
    r = n % total
    cumulative = 0
    for i, c in enumerate(counters):
        cumulative += c
        if r < cumulative:
            return i
    raise AssertionError("cumulative walk fell through — unreachable when r < total")


def const(byte):
    return bytes([byte]) * 32


def progressive(offset):
    return bytes((offset + i) & 0xFF for i in range(32))


def build():
    derive_vectors = []

    # Shape 1 — constant bytes, first seat of the pool.
    derive_vectors.append(
        {
            "name": "constant_bytes_index_0",
            "note": "Constant-byte inputs at the first seat. Mirrors the old crate's launch-state vector.",
            "vrf_seed": const(0x01).hex(),
            "slot_hash": const(0x02).hex(),
            "entry_index": 0,
            "pool_pubkey": const(0x03).hex(),
            "player_pubkey": const(0x04).hex(),
        }
    )

    # Shape 2 — constant bytes, LAST seat of the pool (index 63 of 64). The old
    # crate's equivalent vector used index 420, the old product's bag size.
    derive_vectors.append(
        {
            "name": "constant_bytes_index_63",
            "note": "Constant-byte inputs at the last seat (index 63 of 64 — the entry that seals the pool).",
            "vrf_seed": const(0xAA).hex(),
            "slot_hash": const(0xBB).hex(),
            "entry_index": CAPACITY - 1,
            "pool_pubkey": const(0xCC).hex(),
            "player_pubkey": const(0xDD).hex(),
        }
    )

    # Shape 3 — progressive bytes, so a byte-order bug that a constant-byte input
    # cannot see (every byte identical) shows up immediately.
    derive_vectors.append(
        {
            "name": "progressive_bytes_index_1",
            "note": "Distinct progressive bytes per input. Catches an input-ordering bug that constant-byte vectors are blind to.",
            "vrf_seed": progressive(0).hex(),
            "slot_hash": progressive(32).hex(),
            "entry_index": 1,
            "pool_pubkey": progressive(64).hex(),
            "player_pubkey": progressive(96).hex(),
        }
    )

    for v in derive_vectors:
        v["expected"] = derive_class_randomness(
            bytes.fromhex(v["vrf_seed"]),
            bytes.fromhex(v["slot_hash"]),
            v["entry_index"],
            bytes.fromhex(v["pool_pubkey"]),
            bytes.fromhex(v["player_pubkey"]),
        ).hex()

    # One draw vector per class. `n` is chosen so `n % 64` lands mid-range rather
    # than on a boundary, except for Titan whose range is a single value.
    draw_inputs = [
        (10, "mid-range of Goblin's [0, 38)"),
        (45, "mid-range of Knight's [38, 53)"),
        (55, "mid-range of Wizard's [53, 60)"),
        (61, "mid-range of Dragon's [60, 63)"),
        (63, "Titan's [63, 64) — a single value, the only seat that draws it"),
    ]

    draw_vectors = []
    for n, note in draw_inputs:
        idx = expected_class_index(n, CLASS_COUNTERS)
        draw_vectors.append(
            {
                "name": f"class_index_{idx}_{CLASS_NAMES[idx].lower()}",
                "note": note,
                "n": n,
                "rng_bytes": (n.to_bytes(8, "little") + bytes(24)).hex(),
                "expected_index": idx,
                "expected_class": CLASS_NAMES[idx],
            }
        )

    # Every class must be pinned by exactly one vector — a generator bug that
    # silently dropped one would otherwise weaken the suite without failing it.
    covered = sorted(v["expected_index"] for v in draw_vectors)
    assert covered == list(range(len(CLASS_COUNTERS))), f"draw vectors must cover every class, got {covered}"

    return {
        "_comment": (
            "GENERATED FILE — do not edit by hand. Regenerate with "
            "`python3 fixtures/gen_vectors.py --write` from the crate root. "
            "Digests are computed by Python hashlib, NOT by this crate, so they are "
            "an independent check on byte order and input order."
        ),
        "canonical_input_order": (
            "vrf_seed(32) || slot_hash(32) || entry_index(2, LE) || pool_pubkey(32) || player_pubkey(32) = 130 bytes"
        ),
        "class_names": CLASS_NAMES,
        "class_counters": CLASS_COUNTERS,
        "capacity": CAPACITY,
        "derive": derive_vectors,
        "draw": draw_vectors,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="write fixtures/vectors.json next to this script instead of printing to stdout",
    )
    args = parser.parse_args()

    payload = json.dumps(build(), indent=2) + "\n"

    if args.write:
        out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.json")
        with open(out, "w") as fh:
            fh.write(payload)
        print(f"wrote {out}", file=sys.stderr)
    else:
        sys.stdout.write(payload)


if __name__ == "__main__":
    main()
