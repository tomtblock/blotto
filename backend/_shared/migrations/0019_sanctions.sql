-- 0019 — the two halves of screening that nothing off chain could see
-- (audit 2026-09-11: B-36, and D-20 / F-08).
--
-- 1. `sanctions_refusals` — the record of an entry refused at the gate.
--
-- A wallet on a published sanctions list was refused a packet and the only
-- trace was one line on standard output: no wallet, no list name, nothing
-- written anywhere. A refused entry is the one event a regulator asks about
-- by name, and ours survived exactly as long as the platform's log retention.
--
-- WHAT IS HELD, AND WHY IT IS NOT MORE. The wallet and the pool are public
-- keys and are the subject of the decision. `matches` is the evidence —
-- which list, which listed party, and that source's own identifier for the
-- listing. `consulted` and `failed` keep a refusal decided on one source
-- while two were down legible after the fact. `country` is the geo input to
-- the same decision. `ip_prefix` is TRUNCATED to the first two octets of a
-- v4 address or the first hextet of a v6, which is exactly what this
-- repository writes to its logs (`backend/packet/src/service.ts`,
-- `ipPrefix`) — a store that outlives a log must not quietly hold more than
-- the log did, and nothing in the decision reads the remaining octets.
-- Nothing else about the request is kept: no headers, no device identifier,
-- no allocation. This table is not a general request log and must not become
-- one.
--
-- RETENTION is an operator and counsel question. This schema keeps rows for
-- ever and nothing deletes from them; whoever sets a policy sets it here.
--
-- 2. `entries.sanctions_hold` — the projection of the on-chain hold.
--
-- `SanctionsHoldPlaced` / `SanctionsHoldLifted` have been emitted by the
-- program since Stage F with no decoder, so no ledger row, so no derived
-- column: `lift_sanctions_hold`, the one instruction that can free a held
-- share, could not be aimed from any operator tool, and a held player's
-- results page could not say why their prize had not moved. The decoders
-- landed with this migration; the column is where the projection puts them.
-- It is deliberately NOT `flagged`: a hold is not a reviewable integrity
-- flag, and only an admin-signed lift clears it.
--
-- Forward-only. Never edit an applied migration; new schema is a
-- higher-numbered file. See migrations/README.md.

CREATE TABLE IF NOT EXISTS sanctions_refusals (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Which service refused. `packet` at entry today; the settlement daemon
  -- holds a payment rather than refusing one, and records that on chain.
  service     TEXT        NOT NULL,
  wallet      TEXT        NOT NULL,
  pool        TEXT        NOT NULL,
  -- The screener's own timestamp for the verdict, not ours.
  screened_at TIMESTAMPTZ NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- [{source, listName, entityName, entityId}] — the matched listings.
  matches     JSONB       NOT NULL,
  consulted   TEXT[]      NOT NULL,
  failed      TEXT[]      NOT NULL,
  country     TEXT,
  ip_prefix   TEXT
);

-- "Has this wallet been refused before, and when" is the question this table
-- is asked; both indexes serve it.
CREATE INDEX IF NOT EXISTS sanctions_refusals_wallet_idx ON sanctions_refusals (wallet);
CREATE INDEX IF NOT EXISTS sanctions_refusals_screened_at_idx ON sanctions_refusals (screened_at);

-- The derived half. DEFAULT FALSE is right for both existing and new rows:
-- an entry with no hold event is not held.
ALTER TABLE entries ADD COLUMN IF NOT EXISTS sanctions_hold BOOLEAN NOT NULL DEFAULT FALSE;
-- Unix seconds, as the event carries them (decimal strings end to end).
ALTER TABLE entries ADD COLUMN IF NOT EXISTS sanctions_hold_at NUMERIC;

-- Held entries are a short list that an operator tool scans across pools.
CREATE INDEX IF NOT EXISTS entries_sanctions_hold_idx ON entries (sanctions_hold)
  WHERE sanctions_hold;

