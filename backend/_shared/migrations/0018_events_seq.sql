-- 0018 — a monotonic insertion sequence on `events` (audit F-19), so the
-- ledger replays in an order that is stable and, for rows the backfill wrote,
-- is chain order.
--
-- THE DEFECT. Three call sites replayed the ledger with
-- `ORDER BY slot, signature, event_index`, and the in-memory reference store
-- sorted the same way. `event_index` is the ordinal within ONE transaction's
-- logs, so it orders nothing across transactions; `signature` is a base58
-- transaction signature, which is a hash. Two of our transactions in the same
-- slot therefore replayed in an order decided by base58 collation — a per-pair
-- coin-flip, uncorrelated with the order the chain executed them in and
-- uncorrelated with the order the live run applied them in. The projection is
-- order-dependent (see `projection.ts`), and both stores' comments call the
-- replay order "load-bearing" precisely because a rebuild must reproduce what
-- the live run saw. It could not.
--
-- The table carried no intra-slot position to order by: no transaction index,
-- no log index, no insertion id. Neither ingest path captures one either — the
-- webhook sees signature, logs and slot; `getSignaturesForAddress` returns
-- `{signature, slot, err}` — so the position has to be recorded by us, at
-- append time.
--
-- THE FIX. `seq` is assigned by the database at INSERT, so it is the order the
-- rows were appended in. The replay order becomes `ORDER BY slot, seq`.
--
-- WHAT THIS BUYS, EXACTLY:
--   * Determinism. The same ledger replays the same way every time, so a
--     rebuild is reproducible and two rebuilds of one ledger agree.
--   * Chain order for backfilled rows. `runBackfill` now ingests oldest-first
--     (same audit), so its rows are appended in the order the chain executed
--     them, intra-slot order included.
--   * For two LIVE webhook deliveries that share a slot, `seq` is delivery
--     order. That is not the same thing as chain order and this migration does
--     not claim it is: the webhook payload carries no intra-slot position, so
--     the chain never tells us. Delivery order is stable, recorded, and
--     replayable; it is the honest limit of what we can know from the data we
--     receive. A later backfill over those same slots does not correct it
--     either — those rows are already in the ledger and re-ingest as
--     duplicates.
--
-- The backfill of existing rows uses the OLD replay order
-- (slot, signature, event_index) on purpose. It is arbitrary with respect to
-- the chain — that is the defect — but it is the order the derived tables in
-- any live database were last built from, so the first replay after this
-- migration reproduces exactly the rows that are already being served. A
-- different choice (say `ingested_at`) would change derived rows as a side
-- effect of a schema change, and for any ledger written by the old
-- newest-first backfill it would be strictly worse: it would preserve the
-- REVERSE of chain order rather than merely an arbitrary one.
--
-- Cost: the UPDATE below rewrites every existing row once, inside this
-- migration's transaction. It is O(ledger) and runs at boot on the deployment
-- path, so on a large ledger apply it deliberately rather than during a
-- deploy that is being watched for its health check.
--
-- THIS MIGRATION CARRIES NO RE-DERIVE MARKER, deliberately. (The marker is
-- the declaration a migration makes when it has emptied the derived tables;
-- `REDERIVE_MARKER` in backend/indexer/src/migrate.ts is the text, and
-- 0004_seat_payouts.sql is the worked example. It is spelled out neither here
-- nor in any other file that does not mean it: the checker reads comments, so
-- quoting the marker in prose declares it.) This migration touches no derived
-- table, and because existing rows are numbered in the OLD replay order, the
-- first replay after it produces byte-for-byte the derived rows that were
-- already being served. There is nothing to rebuild.
--
-- Forward-only. Never edit an applied migration; new schema is a
-- higher-numbered file. See migrations/README.md.

-- Nullable first: adding a column with no default is metadata-only, so the
-- table is not rewritten until the UPDATE below, which does it once.
ALTER TABLE events ADD COLUMN IF NOT EXISTS seq BIGINT;

-- Deterministic backfill of existing rows, in the order the old replay used.
-- `row_number()` numbers from 1, and the identity sequence below is set to
-- continue past the highest value written here.
WITH ordered AS (
  SELECT signature,
         event_index,
         row_number() OVER (ORDER BY slot, signature, event_index) AS rn
    FROM events
)
UPDATE events e
   SET seq = o.rn
  FROM ordered o
 WHERE e.signature = o.signature
   AND e.event_index = o.event_index
   AND e.seq IS NULL;

ALTER TABLE events ALTER COLUMN seq SET NOT NULL;

-- GENERATED BY DEFAULT, not ALWAYS: nothing in this service ever writes `seq`
-- (the INSERT in `store-pg.ts` names its columns and `seq` is not among them),
-- and BY DEFAULT keeps a logical restore able to reload the recorded values
-- rather than renumbering them. Renumbering a restored ledger would silently
-- change its replay order, which is the whole thing this column exists to
-- pin down.
ALTER TABLE events ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;

-- Adding an identity to a populated column starts its sequence at 1, which
-- would hand out values already in use. Continue from the highest backfilled
-- value instead. `false` means "this value has not been handed out yet", so
-- the next append takes MAX(seq) + 1; on an empty ledger it takes 1.
SELECT setval(
  pg_get_serial_sequence('events', 'seq'),
  COALESCE((SELECT MAX(seq) FROM events), 0) + 1,
  false
);

-- The replay: an ordered scan of the whole ledger, `ORDER BY slot, seq`.
-- `events_slot_idx` (0001) stays — it is a prefix of this one, and dropping an
-- index is a change with its own risk profile that does not belong bundled
-- into a correctness fix.
CREATE INDEX IF NOT EXISTS events_replay_idx ON events (slot, seq);
