#!/usr/bin/env python3
"""Rust and TypeScript say the same thing, or CI goes red.

WHY THIS EXISTS (audit 2026-09-11, finding F-11, and the regression of
2026-09-12 that proved its shape).

Two kinds of fact live in this repository twice, in two languages, kept in
step by hand:

  1. CONSTANTS. `constants.rs` is the authority for the pool's shape, the
     launch price and pot tables, the paid places and the band table; the
     TypeScript engine, the shared account decoder and the digest module all
     carry mirrors of them. The rent cushion every prize vault is funded with
     is the same kind of fact, pinned in the LiteSVM suite against the
     compiled program.
  2. EVENT LAYOUTS. There is no committed IDL: the `#[event]` structs ARE the
     wire contract, and `backend/_shared/src/blotto-events.ts` mirrors each
     one field for field, in declaration order, with the Borsh reader that
     matches its type. A field inserted in Rust and not in TypeScript does
     not fail to decode — it decodes the REST OF THE EVENT WRONG, silently,
     because every later field is read from the wrong offset.

Nothing compared the two languages until now. On 2026-09-12 a change to the
program's open-gate arithmetic moved a figure in Rust and three TypeScript
mirrors of it were missed; every lane stayed green, and the keeper would have
sent `open_pool` on a tier the program refuses, every tick, paying a fee each
time. The cross-language fixture that existed (`lifecycle-logs.json`) could
not have caught it: it is a snapshot regenerated by the same code it checks.

WHAT IT CANNOT DO. The constant table below is a LIST, so a mirror nobody
adds to it is still unchecked — the check catches drift in a declared pair,
not the appearance of an undeclared one. Adding a mirror means adding a row
here; that is the price of hand-mirroring, and it is much lower than the
price of the drift. A generated IDL would let the event half be derived
rather than listed, and is the better answer whenever `anchor build`'s
artifact is committed — the event half of this file becomes redundant then,
not before.

  exit 0   the two languages agree
  exit 1   they do not; every disagreement is printed
  exit 2   the checker itself is broken (--self-test failed)
"""

