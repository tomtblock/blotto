# Half two: the event layouts.
# ---------------------------------------------------------------------------
def rust_events(text):
    """{event name: [(field, type-with-no-spaces), …]} from one Rust file."""
    out = {}
    for m in re.finditer(r"#\[event\]\s*pub\s+struct\s+(\w+)\s*\{(.*?)\n\}", text, flags=re.S):
        name, body = m.group(1), m.group(2)
        fields = []
        for line in body.splitlines():
            fm = re.match(r"\s*pub\s+(\w+)\s*:\s*(.+?),\s*$", line)
            if fm:
                fields.append((fm.group(1), re.sub(r"\s+", "", fm.group(2))))
        out[name] = fields
    return out


def _balanced_block(text, start):
    """Text of the parenthesised call beginning at `text[start] == '('`."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    return text[start:]


def ts_events(text):
    """{event name: [(field, reader method or None), …]} from the decoder module.

    Two shapes are in use. The common one is an object literal, where the
    reader method is visible per field and can be type-checked against the
    Rust type. The other is a statement body (the two events carrying a
    `Vec`), where the fields are locals and the ORDER is the returned
    object's key order; there the method is not attributable per field, so
    the name and its position are what get checked. Both catch the failure
    that matters — a field added, removed or reordered on one side only.
    """
    out = {}
    for m in re.finditer(r"layout\(\s*'(\w+)'\s*,", text):
        call = _balanced_block(text, m.start() + len("layout"))
        arrow = call.find("=>")
        body = call[arrow + 2 :].strip() if arrow >= 0 else ""
        fields = []
        if body.startswith("("):
            for line in body.splitlines():
                fm = re.match(r"\s*(\w+)\s*:\s*(.+?),\s*$", line)
                if not fm:
                    continue
                rm = re.match(r"r\.(\w+)\(", fm.group(2))
                # A field whose value is not a bare reader call — the
                # fixed-length array `Array.from({length: 7}, () => r.bool())`
                # is the only one today — still has a name and a position,
                # which is what the order check needs; its type is simply not
                # attributable to one reader method.
                fields.append((fm.group(1), rm.group(1) if rm else None))
        else:
            rm = re.search(r"return\s*\{(.*?)\};", body, flags=re.S)
            if rm:
                for part in rm.group(1).split(","):
                    part = part.strip()
                    if not part:
                        continue
                    key = part.split(":")[0].strip()
                    if re.fullmatch(r"\w+", key):
                        fields.append((key, None))
        out[m.group(1)] = fields
    return out


def check_events(rust_texts, ts_text):
    """rust_texts: {path: text}. Returns a list of problem strings."""
    problems = []
    rust = {}
    for path, text in sorted(rust_texts.items()):
        for name, fields in rust_events(strip_comments(text)).items():
            rust[name] = (path, fields)
    ts = ts_events(strip_comments(ts_text))

    if not rust:
        return [f"{EVENT_RUST_DIR}: no #[event] struct found at all — nothing was checked"]
    if not ts:
        return [f"{EVENT_TS_FILE}: no layout() registration found at all — nothing was checked"]

    for name in sorted(set(rust) - set(ts)):
        problems.append(
            f"DRIFT: {rust[name][0]} declares event {name} and {EVENT_TS_FILE} has no decoder "
            f"for it — the indexer would ignore every one emitted"
        )
    for name in sorted(set(ts) - set(rust)):
        problems.append(
            f"DRIFT: {EVENT_TS_FILE} decodes {name} and no #[event] struct declares it"
        )

    for name in sorted(set(rust) & set(ts)):
        path, rfields = rust[name]
        tfields = ts[name]
        rnames = [f for f, _ in rfields]
        tnames = [f for f, _ in tfields]
        if rnames != tnames:
            problems.append(
                f"DRIFT: {name} fields disagree\n"
                f"         {path}: {rnames}\n"
                f"         {EVENT_TS_FILE}: {tnames}\n"
                f"         Order is part of the wire contract: one extra field on either "
                f"side reads every later field from the wrong offset."
            )
            continue
        for (fname, rtype), (_, reader) in zip(rfields, tfields):
            if reader is None:
                continue  # statement-body layout: name and order only
            want = TYPE_FOR_READER.get(reader)
            if want is None:
                problems.append(
                    f"{EVENT_TS_FILE}: {name}.{fname} uses reader r.{reader}(), which this "
                    f"check has no Rust type for — add it to TYPE_FOR_READER"
                )
            elif want != rtype:
                problems.append(
                    f"DRIFT: {name}.{fname} is {rtype} in {path} but is decoded with "
                    f"r.{reader}() (a {want}) in {EVENT_TS_FILE}"
                )
    return problems


# ---------------------------------------------------------------------------
# Self-test. The checker is pure — texts in, problems out — precisely so
# that drift it has never seen can be handed to it on demand.
# ---------------------------------------------------------------------------
RUST_PROBE = """
#[event]
pub struct Started {
    pub pool: Pubkey,
    pub seat: u16,
    pub digest: [u8; 32],
}

#[event]
pub struct Finished {
    pub pool: Pubkey,
    pub total: u64,
}
"""

TS_PROBE_GOOD = """
  layout('Started', (r) => ({
    pool: r.pubkey(),
    seat: r.u16(),
    digest: r.bytes32hex(),
  }));
  layout('Finished', (r) => {
    const pool = r.pubkey();
    const total = r.u64();
    return { pool, total };
  });
"""


def self_test(quiet=False):
    failures = []

    def expect(label, got, want_substring):
        if not any(want_substring in p for p in got):
            failures.append(f"{label}: nothing reported matching {want_substring!r}")

    def expect_clean(label, got):
        if got:
            failures.append(f"{label}: expected no problems, got {got}")

    # --- constants -----------------------------------------------------
    rust_src = "pub const SEATS: u16 = 52;\npub const TABLE: [u64; 2] = [1_000, 2_000];\n"
    files = {
        "programs/blotto_cup/src/constants.rs": rust_src,
        "tests/litesvm/src/lib.rs": "pub const VAULT_RENT_CUSHION: u64 = 890_880;\n",
    }

    def read_of(extra):
        merged = dict(files)
        merged.update(extra)
        return lambda p: merged.get(p)

    global CONSTANT_MIRRORS
    saved = CONSTANT_MIRRORS
    try:
        CONSTANT_MIRRORS = [
            ("programs/blotto_cup/src/constants.rs", "SEATS", [("m.ts", "SEATS")]),
            ("programs/blotto_cup/src/constants.rs", "TABLE", [("m.ts", "TABLE")]),
            ("tests/litesvm/src/lib.rs", "VAULT_RENT_CUSHION", [("m.ts", "cushionLamports")]),
        ]
        agreeing = "export const SEATS = 52n;\nexport const TABLE = [1_000n, 2_000n];\n  cushionLamports = 890_880n;\n"
        expect_clean("constants that agree", check_constants(read_of({"m.ts": agreeing})))

        # The 2026-09-12 regression itself: the Rust figure moved, the mirror
        # did not.
        drifted = agreeing.replace("890_880n", "1_000_000n")
        expect("a moved scalar", check_constants(read_of({"m.ts": drifted})),
               "DRIFT: tests/litesvm/src/lib.rs::VAULT_RENT_CUSHION = 890880")
        # A table whose element changed.
        table_drift = agreeing.replace("2_000n", "2_001n")
        expect("a changed table entry", check_constants(read_of({"m.ts": table_drift})),
               "DRIFT: programs/blotto_cup/src/constants.rs::TABLE")
        # A mirror that was renamed out from under the check.
        renamed = agreeing.replace("export const SEATS", "export const SEAT_COUNT")
        expect("a renamed mirror", check_constants(read_of({"m.ts": renamed})),
               "no declaration of SEATS")
        # An authority file that has moved.
        expect("a missing mirror file", check_constants(read_of({})),
               "m.ts: not found")
        # Arithmetic written differently on the two sides is NOT drift.
        arith_rust = "pub const WINDOW: i64 = 12 * 60 * 60;\n"
        CONSTANT_MIRRORS = [("a.rs", "WINDOW", [("b.ts", "WINDOW")])]
        both = {"a.rs": arith_rust, "b.ts": "export const WINDOW = 12n * 3600n;\n"}
        expect_clean("the same value written two ways", check_constants(lambda p: both.get(p)))
    finally:
        CONSTANT_MIRRORS = saved

    # --- events --------------------------------------------------------
    rp = {"probe.rs": RUST_PROBE}
    expect_clean("events that agree", check_events(rp, TS_PROBE_GOOD))

    expect("a field missing on the TypeScript side",
           check_events(rp, TS_PROBE_GOOD.replace("    seat: r.u16(),\n", "")),
           "DRIFT: Started fields disagree")
    expect("two fields swapped",
           check_events(rp, TS_PROBE_GOOD.replace(
               "    pool: r.pubkey(),\n    seat: r.u16(),",
               "    seat: r.u16(),\n    pool: r.pubkey(),")),
           "DRIFT: Started fields disagree")
    expect("a field read at the wrong width",
           check_events(rp, TS_PROBE_GOOD.replace("seat: r.u16()", "seat: r.u64()")),
           "DRIFT: Started.seat is u16")
    expect("an event with no decoder at all",
           check_events(rp, TS_PROBE_GOOD.replace("'Finished'", "'FinishedX'")),
           "has no decoder for it")
    expect("a decoder for an event that does not exist",
           check_events(rp, TS_PROBE_GOOD.replace("'Finished'", "'FinishedX'")),
           "and no #[event] struct declares it")
    expect("a statement-body layout losing a field",
           check_events(rp, TS_PROBE_GOOD.replace("return { pool, total };", "return { pool };")),
           "DRIFT: Finished fields disagree")
    expect("no Rust events found at all",
           check_events({"probe.rs": "// nothing here\n"}, TS_PROBE_GOOD),
           "nothing was checked")
    expect("no TypeScript layouts found at all",
           check_events(rp, "// nothing here\n"),
           "nothing was checked")

    if failures:
        print("check-mirrors: BROKEN — the checker failed its own self-test.")
        for f in failures:
            print(f"  {f}")
        print()
        print("A comparison that does not fire on deliberate drift is not")
        print("comparing anything. Fix the checker; never delete the probes.")
        return 2
    if not quiet:
        print("check-mirrors self-test: 6 constant cases and 8 event cases correct "
              "(11 of them drift that must be caught).")
    return 0


def main(argv):
    if "--self-test" in argv:
        return self_test()

    root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

    def read(rel):
        path = os.path.join(root, rel)
        try:
            with open(path, encoding="utf-8") as f:
                return f.read()
        except OSError:
            return None

    # The checker reports a verdict only after proving its detector fires —
    # the same order scripts/ci-gate.sh and scripts/check-standing-rules.sh
    # use.
    if self_test(quiet=True) != 0:
        return 2

    problems = check_constants(read)

    rust_dir = os.path.join(root, EVENT_RUST_DIR)
    rust_texts = {}
    for dirpath, _dirs, names in os.walk(rust_dir):
        for n in names:
            if n.endswith(".rs"):
                full = os.path.join(dirpath, n)
                rel = os.path.relpath(full, root)
                with open(full, encoding="utf-8") as f:
                    rust_texts[rel] = f.read()
    ts_text = read(EVENT_TS_FILE)
    if ts_text is None:
        problems.append(f"{EVENT_TS_FILE}: not found — no event layout was checked")
    else:
        problems += check_events(rust_texts, ts_text)

    if problems:
        print()
        print("Rust and TypeScript disagree:")
        print()
        for p in problems:
            print(f"  {p}")
        print()
        print("Change both sides in the same commit. The Rust side is the")
        print("authority: the program is what executes, and the wire contract")
        print("is what it emits.")
        return 1

    print(
        f"mirrors: {len(CONSTANT_MIRRORS)} constants and "
        f"{len(ts_events(strip_comments(ts_text)))} event layouts agree across "
        f"Rust and TypeScript (self-test passed)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
