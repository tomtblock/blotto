# Rust source files that may declare an `#[event]`, and the one TypeScript
# module that decodes them.
EVENT_RUST_DIR = "programs/blotto_cup/src"
EVENT_TS_FILE = "backend/_shared/src/blotto-events.ts"

# Borsh reader method → the Rust type it must be reading. Whitespace is
# stripped from the Rust type before the comparison, so `[u8; 32]` arrives
# here as `[u8;32]`.
TYPE_FOR_READER = {
    "pubkey": "Pubkey",
    "u64": "u64",
    "i64": "i64",
    "u32": "u32",
    "u16": "u16",
    "u8": "u8",
    "bool": "bool",
    "bytes32hex": "[u8;32]",
    "string": "String",
}


# ---------------------------------------------------------------------------
# Text handling. Comments are stripped first: a constant's name appears in
# the doc comment above it at least as often as in the declaration, and a
# brace or paren inside a comment would otherwise confuse the block walker.
# `(?<!:)` keeps `https://` intact.
# ---------------------------------------------------------------------------
def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(?<!:)//[^\n]*", "", text)


def safe_int_expr(expr):
    """Evaluate an integer expression, or a list of them. Nothing else.

    Both languages write these values as arithmetic rather than a literal —
    `12 * 60 * 60` beside `12n * 3600n` — so comparing the source text would
    report drift where there is none. Comparing the VALUES is the point.
    Digit separators and the bigint suffix are normalised away first.
    """
    cleaned = expr.strip()
    cleaned = re.sub(r"\bas const\b", "", cleaned)
    cleaned = re.sub(r"(\d)_(?=\d)", r"\1", cleaned)     # 890_880 → 890880
    cleaned = re.sub(r"(\d)n\b", r"\1", cleaned)          # 1024n   → 1024
    cleaned = cleaned.rstrip(",").strip()
    try:
        node = ast.parse(cleaned, mode="eval").body
    except SyntaxError as exc:
        raise ValueError(f"not an integer expression: {expr!r} ({exc})") from exc

    def ev(n):
        if isinstance(n, ast.Constant) and isinstance(n.value, int) and not isinstance(n.value, bool):
            return n.value
        if isinstance(n, (ast.List, ast.Tuple)):
            return [ev(e) for e in n.elts]
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return -ev(n.operand)
        if isinstance(n, ast.BinOp) and isinstance(n.op, (ast.Add, ast.Sub, ast.Mult, ast.FloorDiv)):
            a, b = ev(n.left), ev(n.right)
            if isinstance(n.op, ast.Add):
                return a + b
            if isinstance(n.op, ast.Sub):
                return a - b
            if isinstance(n.op, ast.Mult):
                return a * b
            return a // b
        raise ValueError(f"not an integer expression: {expr!r}")

    return ev(node)


def find_declaration(text, name):
    """The value expression a Rust or TypeScript declaration binds to `name`.

    Covers `pub const X: T = …;`, `const X: T = …;`, `export const X = …;`
    and the bare property assignment `x = …;` (the fake chain's cushion is a
    field, not a module constant). Non-greedy to the first `;`: an integer
    expression and an array of them contain none.

    The type annotation may contain a `;` — a Rust array type is written
    `[u64; N_TIERS]` — but it may not contain a newline or an `=`, and that
    pair of bounds is what stops the search running on to some unrelated
    assignment further down the file.
    """
    pattern = (
        r"(?:pub\s+)?(?:export\s+)?(?:const|let|var)?\s*\b"
        + re.escape(name)
        + r"\b\s*(?::[^=\n]*?)?\s*=\s*(.*?);"
    )
    m = re.search(pattern, text, flags=re.S)
    return m.group(1) if m else None


