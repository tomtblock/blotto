# Half one: the constants.
# ---------------------------------------------------------------------------
def check_constants(read):
    """`read(path) -> text or None`. Returns a list of problem strings."""
    problems = []
    for src, name, mirrors in CONSTANT_MIRRORS:
        text = read(src)
        if text is None:
            problems.append(f"{src}: not found — {name} has no authority to compare against")
            continue
        expr = find_declaration(strip_comments(text), name)
        if expr is None:
            problems.append(f"{src}: no declaration of {name} (renamed or removed?)")
            continue
        try:
            authority = safe_int_expr(expr)
        except ValueError as exc:
            problems.append(f"{src}::{name}: {exc}")
            continue

        for mpath, mname in mirrors:
            mtext = read(mpath)
            if mtext is None:
                problems.append(f"{mpath}: not found — cannot check the {name} mirror")
                continue
            mexpr = find_declaration(strip_comments(mtext), mname)
            if mexpr is None:
                problems.append(
                    f"{mpath}: no declaration of {mname}, the mirror of {src}::{name}"
                )
                continue
            try:
                mirror = safe_int_expr(mexpr)
            except ValueError as exc:
                problems.append(f"{mpath}::{mname}: {exc}")
                continue
            if mirror != authority:
                problems.append(
                    f"DRIFT: {src}::{name} = {authority} but "
                    f"{mpath}::{mname} = {mirror}"
                )
    return problems


