//! On-chain verification of a results-tree Merkle proof — the first on-chain
//! consumer of `Pool.results_root` (`pay_next_place`, 2026-09-07).
//!
//! The scheme is EXACTLY `backend/scoring/src/merkle.ts` (R20: one scoring
//! module, and this is its verifier, not a second tree):
//!
//! ```text
//! leaf bytes  = player(32) ‖ rank(u8) ‖ amount(u64 LE)          (41 bytes)
//! leaf hash   = sha256(0x00 ‖ leaf bytes)
//! node hash   = sha256(0x01 ‖ left ‖ right)
//! an odd node at any level is PROMOTED unchanged (never duplicated)
//! ```
//!
//! Because a promoted node contributes no step, a proof cannot be derived
//! from a leaf index alone: each step carries its sibling AND which side the
//! sibling is on (`merkle.ts` `ProofStep`). The oracle for the vectors in the
//! tests below is `backend/scoring/fixtures/gen_vectors.py` (Python, R20):
//! the hex constants are copied from `vectors.json`, never captured from
//! this code.

use anchor_lang::prelude::*;
use solana_sha256_hasher::hashv;

/// One proof step, as the TypeScript engine emits it.
#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProofStep {
    pub sibling: [u8; 32],
    /// True when the sibling is the RIGHT child (the accumulator is left).
    pub sibling_on_right: bool,
}

/// The 41-byte leaf preimage `player ‖ rank ‖ amount_le`.
pub fn leaf_bytes(player: &Pubkey, rank: u8, amount: u64) -> [u8; 41] {
    let mut out = [0u8; 41];
    out[..32].copy_from_slice(player.as_ref());
    out[32] = rank;
    out[33..].copy_from_slice(&amount.to_le_bytes());
    out
}

/// `sha256(0x00 ‖ leaf)`.
pub fn hash_leaf(leaf: &[u8; 41]) -> [u8; 32] {
    hashv(&[&[0x00u8], leaf]).to_bytes()
}

/// `sha256(0x01 ‖ left ‖ right)`.
pub fn hash_node(left: &[u8; 32], right: &[u8; 32]) -> [u8; 32] {
    hashv(&[&[0x01u8], left, right]).to_bytes()
}

/// Fold the proof from the leaf hash up; true iff it reaches `root`.
pub fn verify_proof(leaf: &[u8; 41], proof: &[ProofStep], root: &[u8; 32]) -> bool {
    let mut acc = hash_leaf(leaf);
    for step in proof {
        acc = if step.sibling_on_right {
            hash_node(&acc, &step.sibling)
        } else {
            hash_node(&step.sibling, &acc)
        };
    }
    acc == *root
}

#[cfg(test)]
mod tests {
    use super::*;

    fn unhex<const N: usize>(s: &str) -> [u8; N] {
        let mut out = [0u8; N];
        for (i, b) in out.iter_mut().enumerate() {
            *b = u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap();
        }
        out
    }

    /// Two leaves — the smallest tree with a sibling — checked against the
    /// scheme by hand: root = H1(H0(a) ‖ H0(b)).
    #[test]
    fn two_leaf_tree_verifies_both_leaves_and_rejects_a_swapped_side() {
        let a = leaf_bytes(&Pubkey::new_from_array([1u8; 32]), 1, 4_000_000_000);
        let b = leaf_bytes(&Pubkey::new_from_array([2u8; 32]), 2, 0);
        let root = hash_node(&hash_leaf(&a), &hash_leaf(&b));
        let proof_a = [ProofStep {
            sibling: hash_leaf(&b),
            sibling_on_right: true,
        }];
        let proof_b = [ProofStep {
            sibling: hash_leaf(&a),
            sibling_on_right: false,
        }];
        assert!(verify_proof(&a, &proof_a, &root));
        assert!(verify_proof(&b, &proof_b, &root));
        // The side bit is load-bearing: flipping it changes the node.
        let wrong = [ProofStep {
            sibling: hash_leaf(&b),
            sibling_on_right: false,
        }];
        assert!(!verify_proof(&a, &wrong, &root));
        // A tampered amount does not verify.
        let a_tampered = leaf_bytes(&Pubkey::new_from_array([1u8; 32]), 1, 4_000_000_001);
        assert!(!verify_proof(&a_tampered, &proof_a, &root));
    }

    /// Three leaves: the odd third leaf is PROMOTED (no step at level 0),
    /// then paired with the level-1 node. Its proof has ONE step whose
    /// sibling is on the left.
    #[test]
    fn odd_leaf_is_promoted_not_duplicated() {
        let leaves: Vec<[u8; 41]> = (1u8..=3)
            .map(|i| leaf_bytes(&Pubkey::new_from_array([i; 32]), i, 0))
            .collect();
        let h: Vec<[u8; 32]> = leaves.iter().map(hash_leaf).collect();
        let n01 = hash_node(&h[0], &h[1]);
        let root = hash_node(&n01, &h[2]);
        let proof_c = [ProofStep {
            sibling: n01,
            sibling_on_right: false,
        }];
        assert!(verify_proof(&leaves[2], &proof_c, &root));
        // Duplication (the CVE-2012-2459 shape) would give a different root.
        let dup_root = hash_node(&n01, &hash_node(&h[2], &h[2]));
        assert_ne!(dup_root, root);
        assert!(!verify_proof(&leaves[2], &proof_c, &dup_root));
    }

    /// Python-oracle vectors (`merkle_vectors.rs`, generated by
    /// gen_vectors.py from the `full_0` and `field_52` pools in
    /// vectors.json — R20). Pinned as hex so the on-chain verifier is
    /// checked against the same oracle the TypeScript engine is, not against
    /// itself. `field_52` exercises the odd-node carry-up path (52 leaves →
    /// 26 → 13 → 7 → 4 → 2 → 1).
    #[test]
    fn python_oracle_proofs_verify() {
        use super::super::merkle_vectors::{FIELD_52, FULL_0};
        for v in [&FULL_0, &FIELD_52] {
            let root: [u8; 32] = unhex(v.root);
            assert!(!v.cases.is_empty());
            for case in v.cases {
                let player: [u8; 32] = unhex(case.player);
                let leaf = leaf_bytes(&Pubkey::new_from_array(player), case.rank, case.amount);
                let proof: Vec<ProofStep> = case
                    .steps
                    .iter()
                    .map(|(sib, right)| ProofStep {
                        sibling: unhex(sib),
                        sibling_on_right: *right,
                    })
                    .collect();
                assert!(proof.len() <= 6, "a 64-leaf tree needs at most 6 steps");
                assert!(
                    verify_proof(&leaf, &proof, &root),
                    "leaf rank {}",
                    case.rank
                );
                // The same proof against the wrong rank, the wrong amount or
                // a flipped side bit fails.
                let bad_rank = leaf_bytes(
                    &Pubkey::new_from_array(player),
                    case.rank.wrapping_add(1),
                    case.amount,
                );
                assert!(!verify_proof(&bad_rank, &proof, &root));
                let bad_amount = leaf_bytes(
                    &Pubkey::new_from_array(player),
                    case.rank,
                    case.amount.wrapping_add(1),
                );
                assert!(!verify_proof(&bad_amount, &proof, &root));
                let mut flipped = proof.clone();
                flipped[0].sibling_on_right = !flipped[0].sibling_on_right;
                assert!(!verify_proof(&leaf, &flipped, &root));
            }
        }
    }
}
